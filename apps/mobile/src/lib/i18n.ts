import { useAppStore } from './store';

/**
 * Language of the app itself (buttons, titles, settings), chosen per device. Not Silia's language: what she says
 * follows the parent's setting « Langue de Silia » and the page.
 * 'system' = the language of the phone / TV / browser (French, English or Arabic; anything else -> English).
 *
 * The French text is the key: t('Réglages') -> 'Settings' in English. A missing translation shows the French text.
 * {name} in a text is replaced by vars.name.
 */
export type AppLang = 'fr' | 'en' | 'ar';
export type AppLangSetting = AppLang | 'system';

export const APP_LANGS: { value: AppLangSetting; label: string }[] = [
  { value: 'system', label: 'Langue du téléphone' },
  { value: 'fr', label: 'Français' },
  { value: 'en', label: 'English' },
  { value: 'ar', label: 'العربية' },
];

/** The device's own language. */
export function systemLang(): AppLang {
  let tag = 'fr';
  try {
    tag = Intl.DateTimeFormat().resolvedOptions().locale || (globalThis as any).navigator?.language || 'fr';
  } catch {
    tag = (globalThis as any).navigator?.language || 'fr';
  }
  const base = tag.toLowerCase().slice(0, 2);
  return base === 'fr' ? 'fr' : base === 'ar' ? 'ar' : 'en';
}

export function appLang(): AppLang {
  const s = useAppStore.getState().appLang;
  return s && s !== 'system' ? s : systemLang();
}

/** The family's choice (households.app_lang), applied on this device. Unknown values are ignored. */
export function applyFamilyLang(value: unknown) {
  if (value === 'system' || value === 'fr' || value === 'en' || value === 'ar') {
    if (useAppStore.getState().appLang !== value) useAppStore.getState().setAppLang(value);
  }
}

/** Locale for dates. */
export const dateLocale = () => ({ fr: 'fr-FR', en: 'en-GB', ar: 'ar-MA' })[appLang()];

/**
 * Translated text. Screens are remounted when the language changes (root layout), so calling t() while rendering is
 * enough: no hook needed.
 */
export function t(fr: string, vars?: Record<string, string | number>): string {
  const lang = appLang();
  let out = lang === 'fr' ? fr : (DICT[lang][fr] ?? fr);
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}

